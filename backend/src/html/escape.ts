/**
 * Escape a string for safe interpolation into HTML text or attribute values.
 * @param s - The raw string
 * @returns The string with `& < > " '` replaced by their HTML entities
 */
export function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
